@dataclass(frozen=True)  # 아래 클래스를 바꿀 수 없는 데이터 묶음으로 만든다
class Floor:  # 층 하나의 정보
    id: str  # 층 id (예: "b2-1f")
    label: str      # 층 버튼에 쓰는 짧은 이름 (1F, B1 ...)
    name: str       # 화면에 쓰는 이름 (1층, 지하 1층 ...)
