@dataclass(frozen=True)  # 아래 클래스를 바꿀 수 없는 데이터 묶음으로 만든다
class Building:  # 건물 하나의 정보
    id: str  # 건물 id (예: "b2")
    name: str  # 건물 이름 (예: 덕린관)
    sub: str  # 건물 설명 (예: 고등학교 교사)
